"""
Seed the employee database with synthetic (fake) employees.

Usage:
    python seed_employees.py            # makes the total 300 employees
    python seed_employees.py 500        # makes the total 500 employees

Safe to run more than once: it only adds what is missing.
All data is generated by Faker. No real person is involved.
"""

import random
import sys

from faker import Faker

from database import SessionLocal
from models.department import Department
from models.employee import Employee
from models.salary import Salary
from models.user import User  # noqa: F401  (registers the users table)

TARGET = int(sys.argv[1]) if len(sys.argv) > 1 else 300

fake = Faker("en_IN")
Faker.seed(42)       # fixed seeds -> same dataset every time (reproducible)
random.seed(42)

DESIGNATIONS = {
    "IT": ["System Administrator", "Network Engineer", "IT Support Specialist"],
    "Cyber Security": ["Security Analyst", "SOC Engineer", "Penetration Tester"],
    "Software Development": ["Software Developer", "QA Engineer", "DevOps Engineer"],
}
DEFAULT_DESIGNATIONS = ["Associate", "Senior Associate", "Team Lead"]


def main():
    db = SessionLocal()
    try:
        departments = db.query(Department).all()
        if not departments:
            print("No departments found. Create departments first.")
            return

        existing_ids = {e for (e,) in db.query(Employee.employee_id).all()}
        existing_emails = {e for (e,) in db.query(Employee.email).all()}

        current = db.query(Employee).count()
        needed = TARGET - current

        if needed <= 0:
            print(f"Already have {current} employees. Nothing to add.")
            return

        created = 0
        number = 1000

        while created < needed:
            number += 1
            employee_code = f"EMP{number}"

            if employee_code in existing_ids:
                continue

            first = fake.first_name()
            last = fake.last_name()
            email = f"{first}.{last}.{number}@example.com".lower()

            if email in existing_emails:
                continue

            department = random.choice(departments)
            designation = random.choice(
                DESIGNATIONS.get(department.name, DEFAULT_DESIGNATIONS)
            )

            employee = Employee(
                employee_id=employee_code,
                first_name=first,
                last_name=last,
                email=email,
                phone="".join(random.choice("0123456789") for _ in range(10)),
                department_id=department.id,
                designation=designation,
                joining_date=fake.date_between(start_date="-8y", end_date="today"),
                employment_status=random.choices(
                    ["Active", "Inactive"], weights=[92, 8]
                )[0],
            )
            db.add(employee)
            db.flush()  # get employee.id for the salary row

            db.add(
                Salary(
                    employee_id=employee.id,
                    basic_salary=random.randrange(30000, 150001, 500),
                    allowances=random.randrange(2000, 20001, 500),
                    deductions=random.randrange(1000, 12001, 500),
                    currency="INR",
                )
            )

            existing_ids.add(employee_code)
            existing_emails.add(email)
            created += 1

        db.commit()
        total = db.query(Employee).count()
        print(f"Added {created} synthetic employees. Total now: {total}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
